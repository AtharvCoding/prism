def sanity_markdown(rec: dict[str, Any]) -> str:
    d, b = rec["degenerate_task"], rec["beats_random"]
    L = ["# Tier 2 sanity gates (build step 4c)", ""]
    L.append(f"Train and validation only; no test-split row is read. Config `{rec['config']['cfg_id']}`, reward scale "
             f"{rec['settings']['reward_scale']}, **{rec['steps']} steps**, checkpoint every {rec.get('eval_every', '?')} steps, "
             f"seeds {[s['seed'] for s in d['seeds']]}. Written by `scripts/05_train_agents.py --stage sanity` "
             f"(`data/processed/tier2/sanity.json`). **Overall: {'PASS' if rec['passed'] else 'FAIL'}.**")
    L += ["", f"## 1. Degenerate task: {'PASS' if d['passed'] else 'FAIL'}", "",
          "One asset (XLK) with a constant +0.2% daily return, the other twelve zero-mean noise, constant state, real cost model. "
          "Pass: every seed holds XLK at >= 0.85 of the 0.35 cap and earns >= 0.75 of the oracle's log return, on a fresh noise path.", ""]
    rows = [{"seed": s["seed"], "mean XLK weight": round(s["edge_weight_mean"], 4), "of cap": round(s["edge_weight_fraction_of_cap"], 3),
             "agent log return/step": round(s["agent_mean_log_return"], 5), "oracle": round(s["oracle_mean_log_return"], 5),
             "of oracle": round(s["log_return_fraction_of_oracle"], 3), "wall s": round(s["wall_seconds"]), "pass": s["passed"]} for s in d["seeds"]]
    L.append(md_table(pd.DataFrame(rows)))
    L += ["", f"## 2. Beats random on validation: {'PASS' if b['passed'] else 'FAIL'}", "",
          f"V1, real train split, validation-selected checkpoint, against 200 i.i.d.-uniform-action random policies on the real validation "
          f"split (median {_f(b['random_median'], 5)}, max {_f(b['random_max'], 5)}, 95th percentile {_f(b['reported_threshold_mean_log_return'], 5)}). "
          f"Gate: the selected checkpoint beats the median in >= 2 of 3 seeds. A constant equal-weight mix scores "
          f"{_f(b['equal_weight_constant_policy_val'], 5)}, rank {_f(b['equal_weight_constant_percentile_rank'], 2)} among the random policies.", ""]
    rows = []
    for s in b["seeds"]:
        rows.append({"seed": s["seed"], "selected step": s["selected"]["step"],
                     "selected val": round(s["selected"]["val"]["mean_log_return"], 5), "rank": round(s["selected_percentile_rank"], 3),
                     "above median": s["beats_gate_quantile"], "above 95th": s["selected_beats_reported_quantile"],
                     "selected train": round(s["selected"]["train"]["mean_log_return"], 5),
                     "final val": round(s["final"]["val"]["mean_log_return"], 5), "final rank": round(s["final_percentile_rank"], 3),
                     "final train": round(s["final"]["train"]["mean_log_return"], 5)})
    L.append(md_table(pd.DataFrame(rows)))
    L += ["", "Reading (not gating): the final checkpoints fit the train split far better than they predict validation (train mean log return "
          "about +0.02 per decision against about -0.001 to -0.002); the validation-selected checkpoint is often an early one. That overfitting "
          "is the main risk to the Tier 2 result, and the overfitting report measures it for every final run.", "", SANITY_HISTORY]
    return "\n".join(L)
